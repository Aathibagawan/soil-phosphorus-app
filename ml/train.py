"""Train the PSO-CNN-BiLSTM-Attention model and export serving artifacts.

    python -m ml.train                       # synthetic data, full PSO search
    python -m ml.train --quick              # fast smoke run (small search, few epochs)
    python -m ml.train --data my_data.csv   # your own data

Differences from the research notebooks (all deliberate, to make reported
numbers trustworthy):

* Chronological split: train | test (last 20 % of windows, never used for tuning).
* Scalers are fitted on the *training* portion only (notebooks fit on all data).
* PSO scores particles on a *validation* slice carved from the end of the training
  portion (notebooks scored on the test set, i.e. tuned on the test data).
* A Ridge-regression baseline is reported next to the deep model.

Outputs (in --out, default ./artifacts):
    model.keras      trained network
    metadata.json    features, window, scaler params, training ranges, metrics,
                     hyper-parameters, sample window and a test-set curve for the UI
"""
from __future__ import annotations

import argparse
import json
import os
import random
import time
from datetime import datetime, timezone
from pathlib import Path

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import numpy as np
import pandas as pd

from app.features import FEATURES, FEATURE_KEYS

TARGET_ALIASES = ("phosphorus", "p_content", "p")


# --------------------------------------------------------------------------- data
def _norm(name: str) -> str:
    return name.strip().lower().replace(" ", "_")


def load_dataframe(path: str | None, hours: int) -> tuple[pd.DataFrame, str]:
    """Return (df with columns FEATURE_KEYS + 'target', description)."""
    if path:
        raw = pd.read_csv(path)
        source = f"user data: {Path(path).name}"
    else:
        from ml.generate_data import generate
        raw = generate(hours)
        source = "SYNTHETIC data generated by ml/generate_data.py (demo only)"

    raw.columns = [_norm(c) for c in raw.columns]
    if "timestamp" in raw.columns:
        raw = raw.sort_values("timestamp").reset_index(drop=True)

    out = {}
    for f in FEATURES:
        col = next((a for a in f.csv_aliases if a in raw.columns), None)
        if col is None:
            raise SystemExit(f"CSV is missing a column for '{f.key}' (accepted: {f.csv_aliases})")
        out[f.key] = raw[col].astype(float)
    tcol = next((c for c in TARGET_ALIASES if c in raw.columns), None)
    if tcol is None:
        raise SystemExit(f"CSV is missing the target column (one of {TARGET_ALIASES})")
    out["target"] = raw[tcol].astype(float)
    df = pd.DataFrame(out).dropna().reset_index(drop=True)
    return df, source


def make_windows(X: np.ndarray, y: np.ndarray, window: int):
    n = len(X) - window
    Xs = np.stack([X[i:i + window] for i in range(n)])
    ys = y[window:window + n]
    return Xs.astype("float32"), ys.astype("float32")


def metrics(y_true: np.ndarray, y_pred: np.ndarray) -> dict:
    y_true, y_pred = y_true.ravel(), y_pred.ravel()
    err = y_true - y_pred
    ss_res = float(np.sum(err ** 2))
    ss_tot = float(np.sum((y_true - y_true.mean()) ** 2))
    return {
        "rmse": float(np.sqrt(np.mean(err ** 2))),
        "mae": float(np.mean(np.abs(err))),
        "r2": float(1 - ss_res / ss_tot) if ss_tot > 0 else float("nan"),
    }


# --------------------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", help="CSV with sensor columns + Phosphorus (default: synthetic)")
    ap.add_argument("--hours", type=int, default=2000, help="rows of synthetic data")
    ap.add_argument("--window", type=int, default=72)
    ap.add_argument("--out", default="artifacts")
    ap.add_argument("--particles", type=int, default=8)
    ap.add_argument("--iters", type=int, default=10)
    ap.add_argument("--pso-epochs", type=int, default=18)
    ap.add_argument("--epochs", type=int, default=120)
    ap.add_argument("--unit", default="mg/kg", help="unit label for the target in the UI")
    ap.add_argument("--quick", action="store_true", help="tiny search space + few epochs (smoke test)")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    import tensorflow as tf
    import keras
    import pyswarms as ps
    from sklearn.linear_model import Ridge

    from app.layers import build_model

    random.seed(args.seed); np.random.seed(args.seed); tf.random.set_seed(args.seed)

    if args.quick:
        args.particles, args.iters, args.pso_epochs, args.epochs = 3, 2, 4, 25
        lo = np.array([16, 32, 0.0007]); hi = np.array([32, 64, 0.002])
    else:
        lo = np.array([64, 96, 0.0007]); hi = np.array([128, 160, 0.002])

    df, source = load_dataframe(args.data, args.hours)
    W = args.window
    if len(df) < W * 5:
        raise SystemExit(f"Need at least {W * 5} rows; got {len(df)}")
    print(f"[data] {len(df)} rows from {source}")

    # ---- chronological split (windows) --------------------------------------
    n_seq = len(df) - W
    split = int(0.8 * n_seq)                      # first `split` windows = train
    train_rows = split + W                        # rows visible to training windows
    X_raw = df[list(FEATURE_KEYS)].to_numpy(float)
    y_raw = df["target"].to_numpy(float)

    # scalers fitted on training data only
    x_mean, x_std = X_raw[:train_rows].mean(0), X_raw[:train_rows].std(0)
    x_std = np.where(x_std < 1e-9, 1.0, x_std)
    y_train_targets = y_raw[W:split + W]
    y_mean, y_std = float(y_train_targets.mean()), float(y_train_targets.std() or 1.0)

    Xs = (X_raw - x_mean) / x_std
    ys = (y_raw - y_mean) / y_std
    X_seq, y_seq = make_windows(Xs, ys, W)
    X_train, X_test = X_seq[:split], X_seq[split:]
    y_train, y_test = y_seq[:split], y_seq[split:]

    # validation slice (end of training portion) used for PSO + early stopping
    n_fit = int(0.8 * split)
    X_fit, X_val = X_train[:n_fit], X_train[n_fit:]
    y_fit, y_val = y_train[:n_fit], y_train[n_fit:]
    print(f"[split] fit={len(X_fit)} val={len(X_val)} test={len(X_test)} windows")

    def inv(a):  # back to original target units
        return np.asarray(a).reshape(-1) * y_std + y_mean

    # ---- PSO ----------------------------------------------------------------
    def objective(positions: np.ndarray) -> np.ndarray:
        costs = []
        for p in positions:
            filters, units, lr = int(p[0]), int(p[1]), float(p[2])
            keras.backend.clear_session()
            m = build_model(W, len(FEATURE_KEYS), filters, units, lr)
            m.fit(X_fit, y_fit, epochs=args.pso_epochs, batch_size=32, verbose=0)
            pred = m.predict(X_val, verbose=0)
            mt = metrics(inv(y_val), inv(pred))
            cost = mt["rmse"] + (1 - mt["r2"])
            print(f"   [pso] filters={filters:3d} lstm={units:3d} lr={lr:.5f} -> val RMSE={mt['rmse']:.3f} R2={mt['r2']:.3f}")
            costs.append(cost)
        return np.array(costs)

    t0 = time.time()
    print(f"[pso] {args.particles} particles x {args.iters} iterations")
    opt = ps.single.GlobalBestPSO(n_particles=args.particles, dimensions=3,
                                  options={"c1": 1.4, "c2": 1.4, "w": 0.7}, bounds=(lo, hi))
    best_cost, best_pos = opt.optimize(objective, iters=args.iters, verbose=False)
    filters, units, lr = int(best_pos[0]), int(best_pos[1]), float(best_pos[2])
    print(f"[pso] best: filters={filters} lstm_units={units} lr={lr:.5f} (cost {best_cost:.4f}) in {time.time() - t0:.0f}s")

    # ---- final training -----------------------------------------------------
    keras.backend.clear_session()
    model = build_model(W, len(FEATURE_KEYS), filters, units, lr)
    es = keras.callbacks.EarlyStopping(monitor="val_loss", patience=15, restore_best_weights=True)
    hist = model.fit(X_fit, y_fit, validation_data=(X_val, y_val), epochs=args.epochs,
                     batch_size=32, callbacks=[es], verbose=2)

    # ---- evaluation on untouched test windows --------------------------------
    pred_test = inv(model.predict(X_test, verbose=0))
    true_test = inv(y_test)
    m_test = metrics(true_test, pred_test)

    ridge = Ridge(alpha=1.0).fit(X_fit.reshape(len(X_fit), -1), y_fit.ravel())
    m_ridge = metrics(true_test, inv(ridge.predict(X_test.reshape(len(X_test), -1))))
    m_mean = metrics(true_test, np.full_like(true_test, y_train_targets.mean()))

    print(f"[test] deep model : {m_test}")
    print(f"[test] ridge base : {m_ridge}")
    print(f"[test] mean base  : {m_mean}")

    # ---- export ---------------------------------------------------------------
    out = Path(args.out); out.mkdir(parents=True, exist_ok=True)
    model.save(out / "model.keras")

    raw_train = X_raw[:train_rows]
    sample_i = len(X_test) // 2
    sample_start = split + sample_i
    curve_idx = np.linspace(0, len(true_test) - 1, min(200, len(true_test))).astype(int)

    meta = {
        "model_version": datetime.now(timezone.utc).strftime("%Y.%m.%d-%H%M"),
        "architecture": "PSO-tuned CNN-BiLSTM with additive temporal attention",
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "data_source": source,
        "synthetic_data": args.data is None,
        "window": W,
        "features": list(FEATURE_KEYS),
        "target_unit": args.unit,
        "scaler_x": {"mean": x_mean.tolist(), "std": x_std.tolist()},
        "scaler_y": {"mean": y_mean, "std": y_std},
        "train_range": {k: {"min": float(raw_train[:, i].min()), "max": float(raw_train[:, i].max()),
                            "mean": float(raw_train[:, i].mean())}
                        for i, k in enumerate(FEATURE_KEYS)},
        "target_range": {"min": float(y_train_targets.min()), "max": float(y_train_targets.max())},
        "hyperparameters": {"cnn_filters": filters, "lstm_units": units, "learning_rate": lr,
                            "pso_particles": args.particles, "pso_iterations": args.iters,
                            "epochs_run": len(hist.history["loss"])},
        "metrics": {"test": m_test, "baseline_ridge": m_ridge, "baseline_mean": m_mean,
                    "n_train_windows": int(len(X_fit)), "n_val_windows": int(len(X_val)),
                    "n_test_windows": int(len(X_test))},
        "sample": {"window": X_raw[sample_start:sample_start + W].round(4).tolist(),
                   "actual_next": float(y_raw[sample_start + W])},
        "test_curve": {"actual": true_test[curve_idx].round(3).tolist(),
                       "predicted": pred_test[curve_idx].round(3).tolist()},
        "loss_curve": {"train": [round(float(v), 5) for v in hist.history["loss"]],
                       "val": [round(float(v), 5) for v in hist.history["val_loss"]]},
    }
    (out / "metadata.json").write_text(json.dumps(meta))
    print(f"[done] wrote {out / 'model.keras'} and {out / 'metadata.json'}")


if __name__ == "__main__":
    main()
